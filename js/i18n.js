const LANG_STORAGE_KEY = "sunpalm-lang";

function getLang() {
  try {
    const saved = localStorage.getItem(LANG_STORAGE_KEY);
    if (saved && LANGUAGES[saved]) return saved;
  } catch (error) {
    // localStorage can be blocked (private mode / file://); fall back to English.
  }
  return "en";
}

function t(key, lang = getLang()) {
  return (TRANSLATIONS[lang] && TRANSLATIONS[lang][key]) || TRANSLATIONS.en[key] || key;
}

function applyLanguage(lang) {
  if (!LANGUAGES[lang]) lang = "en";
  try {
    localStorage.setItem(LANG_STORAGE_KEY, lang);
  } catch (error) {
    // Ignore: the page still switches, it just won't be remembered.
  }

  const info = LANGUAGES[lang];
  const html = document.documentElement;
  html.lang = lang;
  html.dir = info.dir;

  // Arabic needs Bootstrap's RTL build so the grid, dropdowns and spacing flip correctly.
  const bootstrapCss = document.getElementById("bootstrap-css");
  if (bootstrapCss) {
    const wanted = info.dir === "rtl" ? "css/bootstrap.rtl.min.css" : "css/bootstrap.min.css";
    if (!bootstrapCss.getAttribute("href").endsWith(wanted)) bootstrapCss.setAttribute("href", wanted);
  }

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.dataset.i18n, lang);
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.setAttribute("placeholder", t(el.dataset.i18nPlaceholder, lang));
  });
  document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    el.setAttribute("aria-label", t(el.dataset.i18nAria, lang));
  });

  // Dates are written as ISO in the HTML and formatted for the chosen language.
  const dateFormat = new Intl.DateTimeFormat(info.locale, { day: "numeric", month: "long", year: "numeric" });
  document.querySelectorAll("time[datetime]").forEach((el) => {
    const date = new Date(`${el.getAttribute("datetime")}T12:00:00`);
    if (!Number.isNaN(date.getTime())) el.textContent = dateFormat.format(date);
  });

  const pageKey = document.body.dataset.titleKey;
  document.title = pageKey ? `SUN&PALM | ${t(pageKey, lang)}` : `SUN&PALM | ${t("footer.tagline", lang)}`;

  document.querySelectorAll("[data-lang-current]").forEach((el) => {
    el.textContent = info.short;
  });
  document.querySelectorAll("[data-set-lang]").forEach((el) => {
    el.classList.toggle("active", el.dataset.setLang === lang);
  });

  document.dispatchEvent(new CustomEvent("sun:languagechange", { detail: { lang } }));
}
